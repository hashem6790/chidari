    fun citiesOf(province: String): List<City> =
        provinces.firstOrNull { it.name == province }?.cities ?: emptyList()

    fun cityNamesOf(province: String): List<String> = citiesOf(province).map { it.name }

    fun findProvince(province: String): Province? =
        provinces.firstOrNull { it.name == province }

    fun findCity(province: String, city: String): City? =
        citiesOf(province).firstOrNull { it.name == city }

    /** یافتن یک شهر در همه استان‌ها بدون دانستن نام استان. */
    fun findCityAnywhere(city: String): Pair<Province, City>? {
        provinces.forEach { p ->
            p.cities.firstOrNull { it.name == city }?.let { return p to it }
        }
        return null
    }

    /**
     * جست‌وجوی متنی در نام شهرها و استان‌ها.
     * برای کادر جست‌وجوی صفحه انتخاب موقعیت استفاده می‌شود.
     */
    fun search(query: String, limit: Int = 60): List<Pair<Province, City>> {
        val q = query.trim().normalizeFa()
        if (q.isEmpty()) return emptyList()
        val starts = mutableListOf<Pair<Province, City>>()
        val contains = mutableListOf<Pair<Province, City>>()
        provinces.forEach { p ->
            val pn = p.name.normalizeFa()
            p.cities.forEach { c ->
                val cn = c.name.normalizeFa()
                when {
                    cn.startsWith(q) -> starts += p to c
                    cn.contains(q) || pn.contains(q) -> contains += p to c
                }
            }
        }
        return (starts + contains).take(limit)
    }

    /** نزدیک‌ترین (استان، شهر) به مختصات داده‌شده — برای تشخیص خودکار موقعیت با GPS. */
    fun nearestCity(lat: Double, lng: Double): Pair<Province, City>? {
        var best: Pair<Province, City>? = null
        var bestDist = Double.MAX_VALUE
        provinces.forEach { p ->
            p.cities.forEach { c ->
                val d = GeoUtils.distanceKm(lat, lng, c.lat, c.lng)
                if (d < bestDist) {
                    bestDist = d
                    best = p to c
                }
            }
        }
        return best
    }

    /** نزدیک‌ترین شهر به همراه فاصله آن بر حسب کیلومتر. */
    fun nearestCityWithDistance(lat: Double, lng: Double): Triple<Province, City, Double>? {
        val n = nearestCity(lat, lng) ?: return null
        return Triple(n.first, n.second, GeoUtils.distanceKm(lat, lng, n.second.lat, n.second.lng))
    }
}

/**
 * یکسان‌سازی نویسه‌های فارسی/عربی برای جست‌وجوی بهتر:
 * «ي» عربی به «ی»، «ك» عربی به «ک»، حذف نیم‌فاصله و اعراب.
 */
fun String.normalizeFa(): String = buildString {
    this@normalizeFa.forEach { ch ->
        when (ch) {
            'ي', 'ﻯ', 'ﻱ' -> append('ی')
            'ك' -> append('ک')
            'ۀ', 'ة' -> append('ه')
            'أ', 'إ', 'آ', 'ٱ' -> append('ا')
            'ؤ' -> append('و')
            '\u200c', '\u200f', '\u200e' -> Unit            // نیم‌فاصله و کنترل جهت
            in '\u064B'..'\u0652' -> Unit                    // اعراب
            else -> append(ch)
        }
    }
}

/** ابزارهای محاسبات جغرافیایی. */
object GeoUtils {
    private const val EARTH_RADIUS_KM = 6371.0

    /** فاصله دو نقطه روی کره زمین با فرمول هاورساین (کیلومتر). */
    fun distanceKm(lat1: Double, lng1: Double, lat2: Double, lng2: Double): Double {
        val dLat = Math.toRadians(lat2 - lat1)
        val dLng = Math.toRadians(lng2 - lng1)
        val a = Math.sin(dLat / 2) * Math.sin(dLat / 2) +
                Math.cos(Math.toRadians(lat1)) * Math.cos(Math.toRadians(lat2)) *
                Math.sin(dLng / 2) * Math.sin(dLng / 2)
        val c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a))
        return EARTH_RADIUS_KM * c
    }

    /**
     * نمایش خوانا و فارسی فاصله، بر اساس واحد انتخابی کاربر:
     * ۰ = خودکار، ۱ = همیشه کیلومتر، ۲ = همیشه متر
     */
    fun formatDistance(km: Double): String = when (ir.chidari.util.Fa.distanceUnitMode) {
        2 -> "${(km * 1000).toInt()} متر"
        1 -> if (km < 10.0) String.format("%.1f کیلومتر", km) else "${km.toInt()} کیلومتر"
        else -> when {
            km < 1.0 -> "${(km * 1000).toInt()} متر"
            km < 10.0 -> String.format("%.1f کیلومتر", km)
            else -> "${km.toInt()} کیلومتر"
        }
    }

}
