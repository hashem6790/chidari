    suspend fun populate(db: AppDatabase) {
        if (db.storeDao().count() > 0) return
        // کل درج‌ها داخل یک تراکنش تا اولین اجرای برنامه سریع باشد
        db.withTransaction { populateInternal(db) }
    }

    private suspend fun populateInternal(db: AppDatabase) {

        val rnd = Random(20240715)
        val storeDao = db.storeDao()
        val productDao = db.productDao()

        seedCities.forEach { (provinceName, cityName, storeCount) ->
            val city = IranGeo.findCity(provinceName, cityName) ?: return@forEach

            repeat(storeCount) { index ->
                val tpl = templates[(index + cityName.length) % templates.size]
                val brand = brandNames[rnd.nextInt(brandNames.size)]
                val nameFormat = tpl.nameFormats[rnd.nextInt(tpl.nameFormats.size)]
                val storeName = nameFormat.format(brand)

                // پراکندگی تصادفی در شعاع تقریبی ۰ تا ۷ کیلومتر از مرکز شهر
                val latOffset = (rnd.nextDouble() - 0.5) * 0.12
                val lngOffset = (rnd.nextDouble() - 0.5) * 0.14

                val store = StoreEntity(
                    name = storeName,
                    category = tpl.category,
                    province = provinceName,
                    city = cityName,
                    address = "$cityName، ${streets[rnd.nextInt(streets.size)]}، پلاک ${rnd.nextInt(1, 250)}",
                    phone = "0${rnd.nextInt(21, 99)}${rnd.nextInt(30000000, 89999999)}",
                    bio = tpl.bio,
                    lat = city.lat + latOffset,
                    lng = city.lng + lngOffset,
                    coverEmoji = Categories.emojiOf(tpl.category),
                    openHours = tpl.hours,
                    instagram = "@${brandNamesToEn(brand)}_shop",
                    rating = (30 + rnd.nextInt(0, 20)) / 10.0,
                    ratingCount = rnd.nextInt(5, 320)
                )
                val storeId = storeDao.insert(store)

                // هر فروشگاه زیرمجموعه‌ای از محصولات الگو را با قیمت‌های کمی متفاوت عرضه می‌کند
                val products = tpl.products.mapNotNull { spec ->
                    if (rnd.nextInt(100) < 12) return@mapNotNull null // بعضی فروشگاه‌ها بعضی اقلام را ندارند
                    val variation = 0.88 + rnd.nextDouble() * 0.26   // ۱۲٪- تا ۱۴٪+
                    val price = roundPrice((spec.basePrice * variation).toLong())
                    ProductEntity(
                        storeId = storeId,
                        title = spec.title,
                        category = spec.category,
                        price = price,
                        unit = spec.unit,
                        description = spec.desc,
                        specs = spec.specs,
                        available = rnd.nextInt(100) > 8,
                        discountPercent = if (rnd.nextInt(100) < 22) listOf(5, 10, 15, 20)[rnd.nextInt(4)] else 0,
                        emoji = spec.emoji
                    )
                }
                productDao.insertAll(products)
            }
        }
    }

    /** گرد کردن قیمت به نزدیک‌ترین مضرب معنادار. */
    private fun roundPrice(p: Long): Long = when {
        p >= 10_000_000 -> (p / 100_000) * 100_000
        p >= 1_000_000 -> (p / 10_000) * 10_000
        p >= 100_000 -> (p / 1_000) * 1_000
        p >= 10_000 -> (p / 500) * 500
        else -> (p / 100) * 100
    }

